export function getQuestionsForSeasonAndLocation(season: Season, location: Location): QuizQuestion[] {
  return ALL_QUESTIONS.filter(
    (q) => (q.season === season || q.season === 'general') && q.location === location
  );
}

export function getAvailableLocationsForSeason(season: Season): Location[] {
  const locations = new Set<Location>();
  ALL_QUESTIONS.forEach((q) => {
    if (q.season === season || q.season === 'general') {
      locations.add(q.location);
    }
  });
  return Array.from(locations);
}

export function getCurrentSeason(): Season {
  const month = new Date().getMonth() + 1; // 1-12
  if (month >= 3 && month <= 5) return 'spring';
  if (month >= 6 && month <= 8) return 'summer';
  if (month >= 9 && month <= 11) return 'autumn';
  return 'winter';
}
